function openStory(index) {
  currentStoryIndex = index;
  const story = STORIES[index];
  currentPages = paginateStoryText(story.content);
  currentPageIndex = 0;

  renderReadingLeftPanel(story);
  flipPage(renderStoryPageHTML(), "forward");
}

function renderReadingLeftPanel(story) {
  pageLeft.innerHTML = `
    <h2 class="reading-title">${escapeHTML(story.title)}</h2>
    <p class="reading-progress" id="readingProgress">página ${currentPageIndex + 1} de ${currentPages.length}</p>
    <button class="back-button" id="backButton">← voltar para a lista</button>
  `;
  document.getElementById("backButton").addEventListener("click", backToList);
}

function updateProgressLabel() {
  const el = document.getElementById("readingProgress");
  if (el) el.textContent = `página ${currentPageIndex + 1} de ${currentPages.length}`;
}

function renderStoryPageHTML() {
  const isLast = currentPageIndex === currentPages.length - 1;
  const isFirst = currentPageIndex === 0;
  return `
    <div class="story-text">${escapeHTML(currentPages[currentPageIndex])}</div>
    <button class="page-nav page-nav-prev" id="prevPageBtn" aria-label="Página anterior" ${isFirst ? "disabled" : ""}>‹</button>
    <button class="page-nav page-nav-next" id="nextPageBtn" aria-label="Próxima página" ${isLast ? "disabled" : ""}>›</button>
    ${isLast ? '<span class="page-end-note">fim ✦</span>' : ""}
  `;
}

function attachPageNavListeners() {
  const prevBtn = document.getElementById("prevPageBtn");
  const nextBtn = document.getElementById("nextPageBtn");
  if (prevBtn) prevBtn.addEventListener("click", () => turnPage(-1));
  if (nextBtn) nextBtn.addEventListener("click", () => turnPage(1));
}

function turnPage(delta) {
  const target = currentPageIndex + delta;
  if (target < 0 || target > currentPages.length - 1) return;
  currentPageIndex = target;
  updateProgressLabel();
  flipPage(renderStoryPageHTML(), delta > 0 ? "forward" : "backward");
}

function backToList() {
  renderTableOfContents("backward");
}

/* ==========================================================
   Virada de página (efeito de flip 3D)
   ========================================================== */
let isFlipping = false;

function flipPage(newHTML, direction) {
  if (isFlipping) return;
  isFlipping = true;

  const clone = document.createElement("div");
  clone.className = "page-right flip-clone";

  if (direction === "backward") {
    clone.innerHTML = newHTML;
    clone.style.transform = "rotateY(-176deg)";
    pageRightStack.appendChild(clone);
    void clone.offsetWidth;

    requestAnimationFrame(() => {
      clone.style.transition = "transform 0.85s cubic-bezier(.55,.05,.25,1)";
      clone.style.transform = "rotateY(0deg)";
    });

    clone.addEventListener("transitionend", function done() {
      pageRight.innerHTML = newHTML;
      clone.remove();
      isFlipping = false;
      finishFlip();
    }, { once: true });
  } else {
    clone.innerHTML = pageRight.innerHTML;
    clone.style.transform = "rotateY(0deg)";
    pageRightStack.appendChild(clone);
    pageRight.innerHTML = newHTML;
    finishFlip();
    void clone.offsetWidth;

    requestAnimationFrame(() => {
      clone.style.transition = "transform 0.85s cubic-bezier(.55,.05,.25,1)";
      clone.style.transform = "rotateY(-176deg)";
    });

    clone.addEventListener("transitionend", () => {
      clone.remove();
      isFlipping = false;
    }, { once: true });
  }
}

function finishFlip() {
  attachStoryListeners();
  attachPageNavListeners();
}

/* ==========================================================
   Paginação automática
   Divide o texto da história em páginas de acordo com o
   espaço realmente disponível na página direita do livro.
   ========================================================== */
function paginateStoryText(text) {
  const rect = pageRight.getBoundingClientRect();
  const cs = getComputedStyle(pageRight);
  const width = rect.width - parseFloat(cs.paddingLeft) - parseFloat(cs.paddingRight);
  const height = rect.height - parseFloat(cs.paddingTop) - parseFloat(cs.paddingBottom);

  const ruler = document.createElement("div");
  ruler.className = "story-text";
  ruler.style.position = "fixed";
  ruler.style.visibility = "hidden";
  ruler.style.left = "-9999px";
  ruler.style.top = "0";
  ruler.style.width = Math.max(width, 100) + "px";
  ruler.style.height = Math.max(height, 100) + "px";
  document.body.appendChild(ruler);

  const tokens = text.split(/(\s+)/);
  const pages = [];
  let current = "";

  for (const token of tokens) {
    const attempt = current + token;
    ruler.textContent = attempt;
    if (ruler.scrollHeight > ruler.clientHeight && current.trim().length) {
      pages.push(current.trim());
      current = token.trim().length ? token : "";
    } else {
      current = attempt;
    }
  }
  if (current.trim().length) pages.push(current.trim());

  document.body.removeChild(ruler);
  return pages.length ? pages : [text];
}

